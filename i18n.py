_lang = settings.load_user().get("ui_language")
_lang = _lang if _lang in LANGS else DEFAULT


def get_lang():
    return _lang


def set_lang(code, persist=True):
    """Aktive Sprache setzen und (optional) für den nächsten Start merken."""
    global _lang
    if code not in LANGS:
        raise ValueError(f"Unknown language: {code}")
    _lang = code
    if persist:
        settings.save_user(ui_language=code)


def is_first_start():
    """True, solange noch nie eine Sprache gewählt wurde."""
    return settings.load_user().get("ui_language") not in LANGS


def t(key, **kwargs):
    de, en = STRINGS[key]
    text = en if _lang == "en" else de
    return text.format(**kwargs) if kwargs else text
